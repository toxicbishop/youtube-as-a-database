"""seed.py - generate fake customers and encode them into a StaticDB segment.

    python seed.py                 # 1,000 customers
    python seed.py --count 50      # quick smoke test

FAKE DATA ONLY. Names are random combinations, emails use example.com, and phone
numbers use the reserved fictional 555-01xx range.
"""
from __future__ import annotations

import argparse
import random
import time

from store import Store

FIRST = [
    "Aarav", "Maya", "Liam", "Sofia", "Noah", "Zara", "Ethan", "Priya", "Lucas", "Amara",
    "Mateo", "Hana", "Oliver", "Leila", "Kai", "Nina", "Arjun", "Elena", "Omar", "Ivy",
]  # fmt: skip
LAST = [
    "Rao", "Nguyen", "Silva", "Kim", "Okafor", "Mueller", "Hughes", "Sato", "Costa", "Patel",
    "Novak", "Haddad", "Larsen", "Mehta", "Rossi", "Tan", "Ibrahim", "Dubois", "Khan", "Moreau",
]  # fmt: skip
CITIES = ["Bengaluru", "Lisbon", "Austin", "Osaka", "Nairobi", "Toronto", "Berlin", "Lima", "Oslo", "Pune"]
PLANS = ["free", "pro", "enterprise (lol)"]


def make_customer(i: int, rng: random.Random) -> dict:
    first, last = rng.choice(FIRST), rng.choice(LAST)
    return {
        "id": i,
        "name": f"{first} {last}",
        "email": f"{first}.{last}{i}@example.com".lower(),
        "phone": f"+1-555-01{rng.randint(0, 99):02d}",
        "city": rng.choice(CITIES),
        "plan": rng.choice(PLANS),
        "balance": round(rng.uniform(0, 5000), 2),
        "joined": f"20{rng.randint(15, 26)}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}",
        "note": "FAKE DATA - generated by seed.py",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--count", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42, help="RNG seed (same seed, same customers)")
    parser.add_argument("--data-dir", help="defaults to $STATICDB_DIR or ./data")
    parser.add_argument("--crf", type=int, default=18, help="x264 quality (lower = bigger, safer)")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    customers = {i: make_customer(i, rng) for i in range(1, args.count + 1)}

    store = Store(args.data_dir)
    t0 = time.perf_counter()
    seg = store.write_segment(customers, crf=args.crf)
    path = store.video_path(seg)
    print(
        f"Encoded {args.count} fake customers -> {seg.frames} frames "
        f"({seg.frames / seg.fps:.1f}s of static) in {time.perf_counter() - t0:.1f}s"
    )
    print(f"  video: {path} ({path.stat().st_size / 1024:.0f} KiB)")
    print("\nTry it locally right now:")
    print("  uvicorn api:app --reload   then   curl localhost:8000/customer/402")
    print("\nTo make it a real meme:")
    print("  1. Upload the video to YouTube as Unlisted (throwaway channel, fake data only)")
    print(f"  2. python store.py register --segment {seg.name} --video-id <id>")
    print("  3. STATICDB_SOURCE=youtube uvicorn api:app")


if __name__ == "__main__":
    main()
